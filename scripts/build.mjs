import {cp,mkdir,rm,readdir,readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
const root=resolve(import.meta.dirname,'..');
await rm(resolve(root,'dist'),{recursive:true,force:true});
await mkdir(resolve(root,'dist'),{recursive:true});
await cp(resolve(root,'public'),resolve(root,'dist'),{recursive:true});
await writeFile(resolve(root,'dist','.nojekyll'),'');
const files=await readdir(resolve(root,'dist'));
if(!files.includes('index.html'))throw new Error('Missing index.html');
for(const file of ['index.html','app.js','styles.css','catalog.js','store.js']) if(!(await readFile(resolve(root,'dist',file),'utf8')).trim())throw new Error(`Empty ${file}`);
console.log('Built static website → dist/ (GitHub Pages and Sites compatible)');
